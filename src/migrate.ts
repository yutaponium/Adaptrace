// migrate-dates (ADR-029): a bundle that relied on git dates gets them
// written into generated once, so it keeps comparing the same way now that
// the git date is no longer read. Run it once; afterwards update generated
// with the content, and validate warns when that is forgotten.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Bundle } from "./bundle";
import { editFrontmatter } from "./frontmatter";
import { git, gitDates, hasContentDate, verifiedRange } from "./history";

export interface DateMigration {
  // Documents to get generated, with the new text.
  changes: { path: string; before: string; text: string; at: string }[];
  // Documents without a date that git has no commit for (new files), or
  // with uncommitted changes, whose content is newer than the last commit.
  uncommitted: string[];
  // Documents whose generated is there but has no readable at: fixed by
  // hand, so the person in by is kept.
  unreadable: string[];
  // Why nothing could be taken from git, if so.
  refused: string | null;
  // Every document already has a date.
  nothingMissing: boolean;
}

export function migrateDates(bundle: Bundle): DateMigration {
  // The same documents missing-generated warns about.
  const missing = [...bundle.concepts.values()].filter(
    (c) => !hasContentDate(c),
  );
  const result: DateMigration = {
    changes: [],
    uncommitted: [],
    unreadable: [],
    refused: null,
    nothingMissing: missing.length === 0,
  };
  if (missing.length === 0) return result;
  if (git(bundle.root, ["rev-parse", "--git-dir"]) === null) {
    result.refused = "not a git repository: write generated by hand";
    return result;
  }
  // A shallow clone dates every file by the one commit it has.
  if (
    git(bundle.root, ["rev-parse", "--is-shallow-repository"])?.trim() ===
    "true"
  ) {
    result.refused =
      "a shallow clone, whose commit dates are not each file's own: run it in a full clone";
    return result;
  }
  const dates = gitDates(bundle.root);
  for (const concept of missing) {
    const g = concept.frontmatter.generated as Record<string, unknown> | null;
    // A generated with by and no at gets an at, keeping its other fields;
    // any other generated (no by, an at that cannot be read) is fixed by
    // hand.
    let fields: Record<string, unknown> = { by: "process:git" };
    if (g !== undefined) {
      if (
        g === null ||
        typeof g !== "object" ||
        typeof g.by !== "string" ||
        g.at !== undefined
      ) {
        result.unreadable.push(concept.path);
        continue;
      }
      fields = { ...g };
    }
    // The date the last update was taken from until now: the last commit,
    // or, for a document never committed, its first review (ADR-021). A
    // document changed since its last commit has no date to take.
    const date = dates.get(concept.path);
    const dirty =
      date !== undefined &&
      git(bundle.root, ["diff", "--quiet", "HEAD", "--", concept.path]) ===
        null;
    const at = dirty
      ? undefined
      : (date?.raw ?? verifiedRange(concept)?.earliest.raw);
    if (at === undefined) {
      result.uncommitted.push(concept.path);
      continue;
    }
    const before = readFileSync(join(bundle.root, concept.path), "utf8");
    const text = editFrontmatter(before, { generated: { ...fields, at } });
    result.changes.push({ path: concept.path, before, text, at });
  }
  return result;
}
